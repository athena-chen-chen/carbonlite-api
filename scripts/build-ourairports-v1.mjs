import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import * as XLSX from 'xlsx';

const [inputPath, outputPath, snapshotDate] = process.argv.slice(2);
if (!inputPath || !outputPath || !/^\d{4}-\d{2}-\d{2}$/.test(snapshotDate ?? '')) {
  throw new Error('Usage: node scripts/build-ourairports-v1.mjs <airports.csv> <output.ts> <YYYY-MM-DD>');
}

const input = readFileSync(inputPath);
const workbook = XLSX.read(input, { type: 'buffer', raw: true, codepage: 65001 });
const worksheet = workbook.Sheets[workbook.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(worksheet, { defval: '', raw: true });
const airports = new Map();

for (const row of rows) {
  const iataCode = String(row.iata_code).trim().toUpperCase();
  const latitudeDeg = Number(row.latitude_deg);
  const longitudeDeg = Number(row.longitude_deg);
  if (!/^[A-Z]{3}$/.test(iataCode) || !Number.isFinite(latitudeDeg) || !Number.isFinite(longitudeDeg)) continue;
  if (airports.has(iataCode)) throw new Error(`Duplicate IATA code in source: ${iataCode}`);
  airports.set(iataCode, {
    iataCode,
    name: String(row.name).trim(),
    latitudeDeg,
    longitudeDeg,
    countryCode: String(row.iso_country).trim(),
    regionCode: String(row.iso_region).trim(),
  });
}

const entries = [...airports.entries()].sort(([left], [right]) => left.localeCompare(right));
const sourceSha256 = createHash('sha256').update(input).digest('hex');
const lines = entries.map(([code, airport]) => `  ${JSON.stringify(code)}: ${JSON.stringify(airport)},`);
const generated = `/* eslint-disable */
/**
 * Generated by scripts/build-ourairports-v1.mjs. Do not edit by hand.
 * Source: OurAirports airports.csv (Public Domain), snapshot ${snapshotDate}
 * Source URL: https://davidmegginson.github.io/ourairports-data/airports.csv
 * Source SHA-256: ${sourceSha256}
 * Inclusion: valid three-letter IATA code plus finite latitude/longitude.
 */
export type AirportCoordinate = {
  iataCode: string;
  name: string;
  latitudeDeg: number;
  longitudeDeg: number;
  countryCode: string;
  regionCode: string;
};

export const AIRPORT_COORDINATE_DATASET = {
  source: 'OurAirports airports.csv (Public Domain)',
  sourceUrl: 'https://davidmegginson.github.io/ourairports-data/airports.csv',
  version: '${snapshotDate}',
  sourceSha256: '${sourceSha256}',
  coordinateBasis: 'WGS84 latitude/longitude decimal degrees',
  inclusionRule: 'valid three-letter IATA code and finite coordinates',
  airportCount: ${entries.length},
} as const;

export const AIRPORTS_V1: Readonly<Record<string, AirportCoordinate>> = Object.freeze({
${lines.join('\n')}
});
`;

writeFileSync(outputPath, generated);
console.log(`Wrote ${entries.length} IATA airports to ${outputPath}`);
